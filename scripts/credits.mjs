#!/usr/bin/env node
// Writes CREDITS.md from the same facts the /credits room shows (fonts from src/exhibits/fonts.ts, libraries from package.json).
import { readFileSync, writeFileSync } from "node:fs";
const fontsTs = readFileSync("src/exhibits/fonts.ts", "utf8");
const fonts = [...fontsTs.matchAll(/^  "([^"]+)": f\d+/gm)].map((m) => m[1]);
const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const repo = JSON.parse(readFileSync("content/repo.json", "utf8"));
const lic = (d) => { try { return JSON.parse(readFileSync(`node_modules/${d}/package.json`, "utf8")).license; } catch { return "see package"; } };
const md = `# Credits

Chain of custody for every asset in motomation-studio. The same list is on the site at /credits/.

## The subject
- **Motomation Design** ${repo.meta.version} (${repo.meta.url}) at commit \`${repo.meta.commit.slice(0, 7)}\`, MIT, ${repo.meta.copyright}. Its ${repo.components.length} components are vendored unchanged in \`src/vendor/motomation/\`. All copy and numbers about it come from \`content/repo.json\`, generated by \`scripts/inventory.mjs\`.

## Typefaces (SIL Open Font License 1.1, self-hosted at build by next/font from Google Fonts)
- Bureau: Anybody, Inter Tight, Fragment Mono
- Exhibits: ${fonts.join(", ")}

## Libraries
${Object.keys(pkg.dependencies).map((d) => `- ${d}: ${lic(d)}`).join("\n")}
${Object.keys(pkg.devDependencies).filter((d) => !d.startsWith("@types")).map((d) => `- ${d} (build only): ${lic(d)}`).join("\n")}

## Images and sound
- No stock photography, illustration or audio files. Every image is SVG, canvas or a shader written for this site; every sound is synthesised with the Web Audio API.
- The wordmark is set from real glyph outlines read at build time with opentype.js.
`;
writeFileSync("CREDITS.md", md);
console.log(`CREDITS.md: ${fonts.length + 3} typefaces`);
